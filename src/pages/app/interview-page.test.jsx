import { screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import { ApiError, apiClient } from "@/lib/api/client";
import InterviewPage from "@/pages/app/interview-page";
import { renderRoute } from "@/test/render";

function makeEvaluation(id, score = 4) {
  return {
    id,
    overall_score: score,
    summary: "Clear structure with a concrete example.",
    strengths: ["Specific example"],
    improvements: [{ area: "Impact", explanation: "Results were vague.", suggestion: "Quantify them." }],
    competency_scores: [
      { competency: "communication", label: "Communication", score, rationale: "Clear." },
    ],
    rubric_version: "2026-10-v1",
    ai_generated: true,
    ai_source: "byok",
    ai_model: "claude-opus-5-5",
    created_at: "2026-10-26T10:00:00Z",
  };
}

function makeSession() {
  return {
    id: 7,
    role_title: "Product Manager",
    job_profile: null,
    mode: "text",
    status: "in_progress",
    question_count: 2,
    current_position: 1,
    max_voice_answer_seconds: 180,
    ai_source: "byok",
    ai_model: "claude-opus-5-5",
    created_at: "2026-10-26T09:00:00Z",
    completed_at: null,
    questions: [1, 2].map((position) => ({
      position,
      text: `Question text number ${position}?`,
      competency: "communication",
      competency_label: "Communication",
      answer: null,
      evaluation: null,
    })),
  };
}

let session;
let posts;

function mockApi({ answer, evaluate } = {}) {
  vi.spyOn(apiClient, "get").mockImplementation(async (url) => {
    if (url === "/interviews/7/") return { data: structuredClone(session) };
    throw new Error(`Unexpected GET ${url}`);
  });
  vi.spyOn(apiClient, "post").mockImplementation(async (url, body) => {
    posts.push({ url, body });
    const match = url.match(/questions\/(\d)\/(answer|evaluate)\/$/);
    const position = Number(match?.[1]);
    const question = session.questions[position - 1];
    if (match?.[2] === "answer") {
      if (answer) await answer(body);
      question.answer = { text: body.text, input_mode: body.input_mode, voice_seconds: null };
      session.current_position = position < session.question_count ? position + 1 : null;
      return { data: question.answer };
    }
    if (match?.[2] === "evaluate") {
      if (evaluate) await evaluate();
      question.evaluation = makeEvaluation(position);
      return { data: question.evaluation };
    }
    throw new Error(`Unexpected POST ${url}`);
  });
}

function renderPage() {
  return renderRoute(<InterviewPage />, {
    path: "/app/interviews/:sessionId",
    initialEntries: ["/app/interviews/7"],
  });
}

beforeEach(() => {
  session = makeSession();
  posts = [];
  window.localStorage.clear();
});

afterEach(() => {
  window.localStorage.clear();
});

describe("InterviewPage", () => {
  it("submits an answer, shows labelled AI feedback, then moves on", async () => {
    mockApi();
    const user = userEvent.setup();
    renderPage();

    expect(await screen.findByText("Question text number 1?")).toBeInTheDocument();
    expect(screen.getByText("Question 1 of 2", { selector: "#interview-progress-label" })).toBeInTheDocument();

    await user.type(screen.getByLabelText("Your answer"), "I prioritised the roadmap by impact.");
    await user.click(screen.getByRole("button", { name: "Submit answer" }));

    expect(await screen.findByText("Clear structure with a concrete example.")).toBeInTheDocument();
    expect(screen.getAllByText("AI-generated").length).toBeGreaterThan(0);
    expect(screen.getByText(/generated by AI \(claude-opus-5-5\)/)).toBeInTheDocument();
    expect(posts.map((post) => post.url)).toEqual([
      "/interviews/7/questions/1/answer/",
      "/interviews/7/questions/1/evaluate/",
    ]);
    expect(posts[0].body).toMatchObject({
      text: "I prioritised the roadmap by impact.",
      input_mode: "text",
      voice_seconds: null,
    });

    await user.click(screen.getByRole("button", { name: /next question/i }));

    expect(await screen.findByText("Question text number 2?")).toBeInTheDocument();
  });

  it("keeps the answer and offers a retry when feedback fails", async () => {
    let failures = 1;
    mockApi({
      evaluate: async () => {
        if (failures-- > 0) {
          throw new ApiError({
            status: 503,
            code: "ai_provider_unavailable",
            message: "The AI provider didn't respond. Please try again in a moment.",
          });
        }
      },
    });
    const user = userEvent.setup();
    renderPage();

    await user.type(await screen.findByLabelText("Your answer"), "My answer.");
    await user.click(screen.getByRole("button", { name: "Submit answer" }));

    const alert = await screen.findByRole("alert");
    expect(alert).toHaveTextContent("Feedback couldn't be generated");
    expect(alert).toHaveTextContent("Your answer is saved.");
    expect(screen.getByRole("button", { name: /skip feedback for now/i })).toBeInTheDocument();

    await user.click(screen.getByRole("button", { name: "Try again" }));

    expect(await screen.findByText("Clear structure with a concrete example.")).toBeInTheDocument();
  });

  it("retries a failed submission with the same idempotency key", async () => {
    let failures = 1;
    mockApi({
      answer: async () => {
        if (failures-- > 0) {
          throw new ApiError({ code: "network_error", message: "We couldn't reach the PrepWise server." });
        }
      },
    });
    const user = userEvent.setup();
    renderPage();

    await user.type(await screen.findByLabelText("Your answer"), "My answer.");
    await user.click(screen.getByRole("button", { name: "Submit answer" }));
    expect(await screen.findByText("Your answer wasn't submitted")).toBeInTheDocument();

    await user.click(screen.getByRole("button", { name: "Submit answer" }));

    await waitFor(() => expect(posts.filter((post) => post.url.endsWith("/answer/"))).toHaveLength(2));
    const [first, second] = posts.filter((post) => post.url.endsWith("/answer/"));
    expect(first.body.idempotency_key).toMatch(/^[0-9a-f-]{36}$/);
    expect(second.body.idempotency_key).toBe(first.body.idempotency_key);
  });

  it("restores an unsent draft after a reload", async () => {
    window.localStorage.setItem("prepwise:draft:7:1", "Half-written answer");
    mockApi();
    renderPage();

    expect(await screen.findByLabelText("Your answer")).toHaveValue("Half-written answer");
  });

  it("shows the summary and review for completed interviews", async () => {
    session.status = "completed";
    session.current_position = null;
    session.questions[0].answer = { text: "Answer one", input_mode: "text", voice_seconds: null };
    session.questions[0].evaluation = makeEvaluation(1, 3);
    mockApi();
    renderPage();

    expect(await screen.findByText("Interview complete")).toBeInTheDocument();
    expect(screen.getByText(/You answered 1 of 2 questions/)).toBeInTheDocument();
    expect(screen.getByText("Not answered.")).toBeInTheDocument();
  });
});
