import { Sparkles } from "lucide-react";

import { Badge } from "@/components/ui/badge";
import { cn } from "@/lib/utils";

function AiGeneratedBadge({ className }) {
  return (
    <Badge variant="default" className={className}>
      <Sparkles aria-hidden="true" />
      AI-generated
    </Badge>
  );
}

/** Standard disclaimer shown with every piece of AI output. */
function AiDisclaimer({ model, kind = "feedback", className }) {
  return (
    <p className={cn("text-xs leading-5 text-muted-foreground", className)}>
      This {kind} was generated by AI{model ? ` (${model})` : ""}. It can be inaccurate or
      incomplete
      {kind === "analysis" ? "" : ", and scores are approximate guidance, not a hiring assessment"}.
      Use your own judgement.
    </p>
  );
}

export { AiDisclaimer, AiGeneratedBadge };
